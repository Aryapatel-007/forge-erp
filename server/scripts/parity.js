// Compares Forge with ERPNext's published list of document types and writes docs/PARITY.md.
// Only names and flags are read from their repository. See docs/erpnext-doctypes.json.
//   node --env-file=.env.test scripts/parity.js
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import '../doctypes/index.js';
import { allTypes } from '../engine/registry.js';
import { reportCount } from '../engine/reports.js';
import { listJobs } from '../engine/scheduler.js';

const here = path.dirname(fileURLToPath(import.meta.url));
const docs = path.join(here, '../../docs');
const flags = JSON.parse(fs.readFileSync(path.join(docs, 'erpnext-doctypes.json'), 'utf8'));

// Theirs -> where the same job is done here, when the name differs.
const { _not_applicable: NOT_APPLICABLE, ...SAME_JOB } = JSON.parse(fs.readFileSync(path.join(here, 'parityMap.json'), 'utf8'));

const pascal = (snake) => snake.split('_').map((w) => w.charAt(0).toUpperCase() + w.slice(1)).join('');
const engineNames = new Set(allTypes().map((t) => t.name));

const groups = new Map();
for (const [key, row] of Object.entries(flags)) {
  const [repo, module, name] = key.split(':');
  if (row.child) continue;
  const group = `${repo === 'hrms' ? 'hrms' : 'erpnext'}/${module}`;
  if (!groups.has(group)) groups.set(group, { have: [], missing: [], settings: 0, notApplicable: [] });
  const entry = groups.get(group);
  const match = engineNames.has(pascal(name)) ? pascal(name) : SAME_JOB[name];
  if (match) entry.have.push(`${name} → ${match}`);
  else if (NOT_APPLICABLE[name]) entry.notApplicable.push(`${name}: ${NOT_APPLICABLE[name]}`);
  else if (row.single) entry.settings += 1;
  else entry.missing.push(name);
}

let have = 0;
let missing = 0;
let settings = 0;
let skipped = 0;
for (const entry of groups.values()) {
  have += entry.have.length;
  missing += entry.missing.length;
  settings += entry.settings;
  skipped += entry.notApplicable.length;
}
const real = Object.values(flags).filter((r) => !r.child).length;
const types = allTypes();
const withLogic = types.filter((t) => t.onSubmit || t.onCancel || t.prepare || t.afterCreate || t.afterUpdate || t.actions.length > 0);
const lines = [
  '# Forge against ERPNext',
  '',
  'Generated by `server/scripts/parity.js`. Do not edit by hand.',
  '',
  `Forge has ${engineNames.size} engine document types, about 30 hand-written ones, ${reportCount() + 13} reports and ${listJobs().length} scheduled jobs.`,
  '',
  `ERPNext and HRMS have ${Object.keys(flags).length} document types, of which ${Object.values(flags).filter((r) => r.child).length} are child tables. Of the other ${real}: **${have} are matched here**, ${skipped} do not apply, ${missing} are missing, and ${settings} unmatched are settings pages.`,
  '',
  '**A match means the same job has a home here. It does not mean every option they have.** ERPNext has had more than a decade of real-world detail, and Forge has not. `docs/STATUS.md` says what has actually been tested.',
  '',
  `Depth: ${withLogic.length} of Forge's ${types.length} engine document types have business logic of their own. The other ${types.length - withLogic.length} are records: they save, validate, link, search, import and report, but do nothing further. Reports: Forge has ${reportCount() + 13}, ERPNext and HRMS have 221.`,
  '',
];
for (const [group, entry] of [...groups.entries()].sort()) {
  lines.push(`## ${group}: ${entry.have.length} matched, ${entry.missing.length} missing${entry.settings ? `, ${entry.settings} settings` : ''}`, '');
  if (entry.missing.length) lines.push(`Missing: ${entry.missing.join(', ')}`, '');
  for (const row of entry.notApplicable) lines.push(`- Does not apply: ${row}`);
  if (entry.notApplicable.length) lines.push('');
}
fs.writeFileSync(path.join(docs, 'PARITY.md'), `${lines.join('\n')}\n`);
console.log(`engine types ${types.length}, with logic ${withLogic.length}, reports ${reportCount() + 13}, jobs ${listJobs().length}`);
console.log(`matched ${have}, not applicable ${skipped}, missing ${missing}, unmatched settings ${settings}, of ${real}`);
for (const [group, entry] of [...groups.entries()].sort()) if (entry.missing.length) console.log(`${group} (${entry.missing.length}): ${entry.missing.join(' ')}`);
process.exit(0);
